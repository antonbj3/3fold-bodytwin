TRUE = np.array([0.3, 1.2, 0.06, 0.03, 0.015])

def operator(p):
    (c1, c2, g, h1, h2) = p
    return np.array([[-(g + h1) / c1, g / c1], [g / c2, -(g + h2) / c2]])

def propagate(p, q, dt, x):
    a = operator(p)
    v = np.array(q) / p[:2]
    M = np.zeros((3, 3))
    M[:2, :2] = a
    M[:2, 2] = v
    return (expm(M * dt) @ np.r_[x, 1.0])[:2]

def fixture(p, kind, step):
    n = int(round(20 / step))
    a = np.zeros((n + 1, 6))
    a[:, 0] = np.arange(n + 1) * step
    a[:, 3] = 22
    x = np.zeros(2)
    for (i, t) in enumerate(a[:, 0]):
        if kind == 'heater':
            power = 1.0 if t < 3 or 8 <= t < 10 else 0.0
            q = np.array([power, 0.0])
            a[i, 4] = power
        else:
            power = 2.0 if t < 10 else 0.0
            q = 0.5 * power * np.array([0.3, 0.7])
            a[i, 5] = power
        a[i, 1:3] = 22 + x
        if i < n:
            x = propagate(p, q, step, x)
    return a

def write_csv(name, a):
    with (ROOT / name).open('w') as f:
        w = csv.writer(f)
        w.writerow(COLS)
        w.writerows(a)

def rate(t):
    return (0.5 if t >= 43 else 0.25) ** (43 - t)

