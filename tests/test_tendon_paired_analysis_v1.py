"""Tests for the I3 paired force+displacement analysis module.

Plain python3:  OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1 \
PYTHONPATH=src python tests/test_tendon_paired_analysis_v1.py
Also pytest-compatible (functions named test_*).

Covers the acceptance items:
  * exact unit conversions (gf->N, mm->m, mm^2->m^2)
  * strain = displacement/reference length, and refusal on a bad length
  * PairedInputs shape/finiteness validation and non-mutation of caller arrays
  * constant-displacement detector: constant/creep/slip/nonmonotonic
  * absolute-parameter gate: ABSTAIN without geometry, PASS with all four
  * KEY (needs BODYTWIN_REF_SLS_SCRIPT, skipped otherwise): paired data from the
    reference SLS script for (a) a constant hold and
    (b) a +2% drifting hold -> fit_tau_from_pairs recovers tau=100 s, E_inf=0.8e9,
    E_branch=0.4e9 within 5%. This is exactly the confound that force-only
    normalized analysis could not resolve.
  * failure test: fit_tau_from_pairs ABSTAINs when area or length is missing
  * apparent_modulus ABSTAINs (with no number) without geometry
  * normalized_relaxation_holds attaches paired strain at the same indices
  * the module self_test is fully green
"""
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The reference SLS script is not part of this repository: it is located by
# BODYTWIN_REF_SLS_SCRIPT (see tests/research_data.py).
SRC = os.path.join(ROOT, "src")
if SRC not in sys.path:
    sys.path.insert(0, SRC)
import numpy as np  # noqa: E402

from bodytwin.cells.musculoskeletal import tendon_paired_analysis_v1 as m  # noqa: E402

_SLS_CACHE = []


def _load_reference_sls():
    """The reference exact SLS propagation (external script); skip when absent."""
    if _SLS_CACHE:
        return _SLS_CACHE[0]
    from research_data import optional_path

    script = optional_path("BODYTWIN_REF_SLS_SCRIPT")
    spec = importlib.util.spec_from_file_location("reference_sls_paired_test", script)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    _SLS_CACHE.append(mod)
    return mod

# Declared synthetic truth for the paired recovery tests (known SLS mathematics).
TAU = 100.0
E_INF = 0.8e9
E_BRANCH = 0.4e9
P = np.array([E_INF, E_BRANCH, TAU])
AREA_MM2 = 57.5
AREA_M2 = AREA_MM2 * 1e-6
REF_MM = 200.0
RAMP_S = 0.5
HOLD_END_S = 300.0
N_SAMPLES = 601
EPS0 = 0.02


def _ramp_hold(drift_frac):
    """Ramp to eps0 in RAMP_S, then hold with linear strain drift over the hold."""
    t = np.linspace(0.0, HOLD_END_S, N_SAMPLES)
    eps = np.empty_like(t)
    for i, ti in enumerate(t):
        if ti <= RAMP_S:
            eps[i] = EPS0 * ti / RAMP_S
        else:
            eps[i] = EPS0 * (1.0 + drift_frac * (ti - RAMP_S) / (HOLD_END_S - RAMP_S))
    return t, eps


def _reference_paired(drift_frac):
    """Clean paired record generated by the reference exact SLS propagation."""
    t, eps = _ramp_hold(drift_frac)
    stress = _load_reference_sls().simulate(t, eps, P)[0]
    force_gf = stress * AREA_M2 / m.m.GF_TO_N
    disp_mm = eps * REF_MM
    return m.PairedInputs(time_s=t, force_gf=force_gf, displacement_mm=disp_mm,
                          reference_length_mm=REF_MM, area_mm2=AREA_MM2,
                          specimen="syn", donor="d")


# --------------------------------------------------------------------- units ----
def test_unit_conversions_exact():
    assert m.m.GF_TO_N == m.m.GF_TO_N == 9.80665e-3
    assert float(m.gf_to_n(1.0)) == 9.80665e-3
    assert abs(float(m.gf_to_n(1000.0)) - 9.80665) < 1e-12
    assert m.MM_PER_M == 1e-3
    assert float(m.mm_to_m(1.0)) == 1e-3
    assert float(m.mm_to_m(250.0)) == 0.25
    assert m.MM2_PER_M2 == 1e-6
    assert float(m.mm2_to_m2(1.0)) == 1e-6
    assert abs(float(m.mm2_to_m2(57.5)) - 5.75e-5) < 1e-15


def test_strain_from_displacement_correctness():
    s = m.strain_from_displacement([1.0, 2.0, 5.0], 1000.0)
    assert np.allclose(s, [1e-3, 2e-3, 5e-3], rtol=0, atol=1e-15)
    # strain is scale-consistent: doubling the length halves the strain
    s2 = m.strain_from_displacement([1.0, 2.0, 5.0], 2000.0)
    assert np.allclose(s2, s / 2.0, rtol=0, atol=1e-18)


def test_strain_from_displacement_refuses_bad_length():
    for bad in (0.0, -1.0, float("nan"), float("inf"), None):
        try:
            m.strain_from_displacement([1.0, 2.0], bad)
            raise AssertionError(f"expected ValueError for reference length {bad!r}")
        except ValueError:
            pass
    # non-finite displacement is refused too
    try:
        m.strain_from_displacement([1.0, float("nan")], 100.0)
        raise AssertionError("expected ValueError for non-finite displacement")
    except ValueError:
        pass


def test_paired_inputs_validates_and_does_not_mutate():
    t = np.linspace(0.0, 10.0, 11)
    f = np.full(11, 100.0)
    d = np.full(11, 1.0)
    # length mismatch refused
    try:
        m.PairedInputs(time_s=t, force_gf=f[:-1], displacement_mm=d)
        raise AssertionError("expected ValueError on length mismatch")
    except ValueError:
        pass
    # non-finite refused
    bad_f = f.copy()
    bad_f[3] = float("nan")
    try:
        m.PairedInputs(time_s=t, force_gf=bad_f, displacement_mm=d)
        raise AssertionError("expected ValueError on non-finite force")
    except ValueError:
        pass
    # bad geometry refused
    for kwargs in ({"area_mm2": 0.0}, {"area_mm2": -1.0},
                   {"reference_length_mm": 0.0}):
        try:
            m.PairedInputs(time_s=t, force_gf=f, displacement_mm=d, **kwargs)
            raise AssertionError(f"expected ValueError for {kwargs}")
        except ValueError:
            pass
    # caller arrays are not mutated / aliased
    before = t.copy()
    inp = m.PairedInputs(time_s=t, force_gf=f, displacement_mm=d,
                         reference_length_mm=100.0, area_mm2=10.0)
    f[:] = -999.0
    assert np.array_equal(t, before)
    assert inp.force_gf[0] == 100.0  # stored copy, unaffected by caller mutation


# ------------------------------------------------- constant-displacement check ----
def test_verify_constant_displacement_classifications():
    t = np.linspace(0.0, 100.0, 201)
    d0 = 5.0
    v = m.verify_constant_displacement(np.full_like(t, d0), t, 10.0, 90.0)
    assert v["classification"] == "constant" and v["constant"] is True
    assert abs(v["drift_rel"]) < 1e-12
    creep = d0 * (1.0 + 0.01 * (t - 10.0) / 80.0)
    vc = m.verify_constant_displacement(creep, t, 10.0, 90.0)
    assert vc["classification"] == "creep" and vc["constant"] is False
    assert abs(vc["drift_rel"] - 0.01) < 1e-9
    slip = d0 * (1.0 - 0.02 * (t - 10.0) / 80.0)
    vs = m.verify_constant_displacement(slip, t, 10.0, 90.0)
    assert vs["classification"] == "slip" and vs["constant"] is False
    assert abs(vs["drift_rel"] + 0.02) < 1e-9
    nonmono = d0 * (1.0 + 0.05 * np.sin(np.linspace(0.0, 6.0 * np.pi, t.size)))
    vn = m.verify_constant_displacement(nonmono, t, 10.0, 90.0)
    assert vn["classification"] == "nonmonotonic" and vn["constant"] is False


def test_verify_constant_displacement_refuses_bad_window():
    t = np.linspace(0.0, 10.0, 11)
    d = np.full_like(t, 1.0)
    for lo, hi in ((5.0, 5.0), (5.0, 4.0), (100.0, 200.0)):
        try:
            m.verify_constant_displacement(d, t, lo, hi)
            raise AssertionError(f"expected ValueError for window ({lo}, {hi})")
        except ValueError:
            pass


# ------------------------------------------------------------- parameter gate ----
def test_absolute_gate_abstains_without_geometry():
    t, eps = _ramp_hold(0.0)
    inp = m.PairedInputs(time_s=t, force_gf=np.full_like(t, 100.0) + eps,
                         displacement_mm=eps * REF_MM, specimen="s", donor="d")
    v = m.absolute_parameter_gate(inp)
    assert v["state"] == "ABSTAIN"
    assert {"area_mm2", "reference_length_mm"} <= set(v["missing"])
    assert "displacement_channel" not in v["missing"]  # paired channel IS present
    assert "not itself" in v["meaning"]


def test_absolute_gate_passes_with_all_four():
    inp = _reference_paired(0.0)
    v = m.absolute_parameter_gate(inp)
    assert v["state"] == "PASS"
    assert set(v["missing"]) == set()
    assert v["inputs_strain_protocol_verified"] is True
    assert v["inputs_displacement_channel"] == "present"
    # an explicit provenance flag overrides the derived value
    prov = m.PairedInputs(time_s=inp.time_s, force_gf=inp.force_gf,
                          displacement_mm=inp.displacement_mm,
                          reference_length_mm=REF_MM, area_mm2=AREA_MM2,
                          provenance={"strain_protocol_verified": False})
    assert m.absolute_parameter_gate(prov)["state"] == "ABSTAIN"


# --------------------------------------------------------- tau from paired data ----
def _assert_tau_recovered(fit, true_tau=TAU, rel=0.05, extra=""):
    assert fit["state"] == "PASS", fit
    got = fit["tau_s"]
    assert abs(got - true_tau) / true_tau < rel, (got, true_tau, extra, fit)
    ci = fit["tau_ci95_s"]
    assert ci is not None and len(ci) == 2, fit
    assert ci[0] - 1e-6 <= true_tau <= ci[1] + 1e-6, (ci, true_tau)


def test_fit_tau_recovers_constant_hold():
    inp = _reference_paired(0.0)
    diag = m.protocol_diagnostic(inp, RAMP_S, HOLD_END_S)
    assert diag["classification"] == "constant"
    fit = m.fit_tau_from_pairs(inp)
    _assert_tau_recovered(fit, extra="constant hold")
    assert abs(fit["e_inf_Pa"] - E_INF) / E_INF < 0.05
    assert abs(fit["e_branch_Pa"] - E_BRANCH) / E_BRANCH < 0.05


def test_fit_tau_recovers_drifting_hold():
    # The decisive case: a +2% hold-strain drift is OBSERVED, so tau is still
    # recoverable. Force-only normalized analysis read this as a richer form.
    inp = _reference_paired(0.02)
    diag = m.protocol_diagnostic(inp, RAMP_S, HOLD_END_S)
    assert diag["classification"] == "creep" and diag["used_strain"] is True
    fit = m.fit_tau_from_pairs(inp)
    _assert_tau_recovered(fit, extra="+2% drifting hold")
    assert abs(fit["e_inf_Pa"] - E_INF) / E_INF < 0.05
    assert abs(fit["e_branch_Pa"] - E_BRANCH) / E_BRANCH < 0.05


def test_fit_tau_abstains_without_geometry():
    t, eps = _ramp_hold(0.0)
    base = dict(time_s=t, force_gf=eps * AREA_M2 / m.m.GF_TO_N,
                displacement_mm=eps * REF_MM)
    # missing area
    no_area = m.PairedInputs(reference_length_mm=REF_MM, **base)
    fit_a = m.fit_tau_from_pairs(no_area)
    assert fit_a["state"] == "ABSTAIN" and "area_mm2" in fit_a["missing"]
    assert "tau_s" not in fit_a
    # missing length
    no_len = m.PairedInputs(area_mm2=AREA_MM2, **base)
    fit_l = m.fit_tau_from_pairs(no_len)
    assert fit_l["state"] == "ABSTAIN" and "reference_length_mm" in fit_l["missing"]
    assert "tau_s" not in fit_l
    # neither
    neither = m.PairedInputs(**base)
    v = m.fit_tau_from_pairs(neither)
    assert v["state"] == "ABSTAIN"
    assert set(v["missing"]) == {"area_mm2", "reference_length_mm"}


# ----------------------------------------------------------- apparent modulus ----
def test_apparent_modulus_abstains_and_reports():
    t, eps = _ramp_hold(0.0)
    no_geo = m.PairedInputs(time_s=t, force_gf=eps * AREA_M2 / m.m.GF_TO_N,
                            displacement_mm=eps * REF_MM)
    v = m.apparent_modulus(no_geo)
    assert v["state"] == "ABSTAIN"
    assert "peak_stress_Pa" not in v and "equilibrium_stress_Pa" not in v
    got = m.apparent_modulus(_reference_paired(0.0))
    assert got["state"] == "PASS"
    assert got["peak_stress_Pa"] > 0.0
    assert got["equilibrium_stress_Pa"] > 0.0
    assert 0.0 < got["equilibrium_fraction_of_peak"] <= 1.0
    assert "no extrapolation" in got["provenance_note"]


# ------------------------------------------------------- normalized paired holds ----
def _two_step_paired():
    tau, beta, c = 13.7, 0.7, 0.35
    dt, duration = 0.03, 410.0
    t = np.arange(0.0, duration, dt)
    peaks, amps = (10.0, 210.0), (1000.0, 1500.0)
    tension = np.full_like(t, c * amps[0])
    for i, (tp, amp) in enumerate(zip(peaks, amps)):
        t_end = peaks[i + 1] if i + 1 < len(peaks) else duration
        sel = (t >= tp) & (t < t_end)
        x = t[sel] - tp
        tension[sel] = c * amp + (1 - c) * amp * np.exp(-np.power(x / tau, beta))
    disp = np.where(t < peaks[0], 0.0,
                    np.where(t < peaks[1], 1.0, 2.0))
    return m.PairedInputs(time_s=t, force_gf=tension, displacement_mm=disp,
                          reference_length_mm=100.0, specimen="syn", donor="d")


def test_normalized_relaxation_holds_attaches_paired_strain():
    holds = m.normalized_relaxation_holds(_two_step_paired(), n_peaks_max=5,
                                          min_hold_s=20.0)
    assert len(holds) == 2, [h["peak_force_gf"] for h in holds]
    for h in holds:
        assert set(("x_s", "y_norm", "peak_force_gf", "peak_strain",
                    "strain_hold_drift_rel")).issubset(h)
        assert h["peak_strain"] is not None
        assert h["peak_strain"] > 0.0
        assert abs(h["strain_hold_drift_rel"]) < 1e-9  # steps are constant holds
        assert h["y_norm"][0] <= 1.0 + 1e-9


def test_normalized_relaxation_holds_single_hold_fallback():
    # a record that is already one hold: no step peaks, post-peak span returned
    n = 400
    t = np.linspace(0.0, 100.0, n)
    tension = 500.0 * np.exp(-t / 30.0)
    disp = np.full(n, 2.0)
    inp = m.PairedInputs(time_s=t, force_gf=tension, displacement_mm=disp,
                         reference_length_mm=100.0)
    holds = m.normalized_relaxation_holds(inp)
    assert len(holds) == 1
    assert holds[0]["single_hold_fallback"] is True
    assert holds[0]["peak_strain"] is not None
    assert holds[0]["n_points"] >= 2


# ------------------------------------------------------------------ self-test ----
def test_module_self_test_all_true():
    out = m.self_test()
    assert out and all(out.values()), out


def _run_all():
    tests = [v for k, v in sorted(globals().items())
             if k.startswith("test_") and callable(v)]
    results, failed = [], []
    for t in tests:
        try:
            t()
            results.append((t.__name__, "PASS"))
        except Exception as exc:  # noqa: BLE001
            results.append((t.__name__, f"FAIL: {exc}"))
            failed.append(t.__name__)
    for name, res in results:
        if res == "PASS":
            print(f"{res:60s} {name}")
        else:
            print(f"{name}: {res}")
    print(f"\n{len(tests) - len(failed)}/{len(tests)} passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(_run_all())
