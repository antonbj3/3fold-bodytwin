# ============================================================================================
# 2. Twitch kernel -- critically damped 2nd-order impulse response, DERIVED not quoted.
#    H(s) = k/(s+a)^2 (double pole) -> h(t) = k*t*exp(-a t), t>=0. Peaks at t=1/a with value
#    k*exp(-1)/a. Setting tau=1/a=T (contraction time) and solving k so peak==P:
#    k = P*e/T  =>  h(t) = P*(t/T)*exp(1 - t/T).
#    Verified numerically: integral over [0,inf) = P*T*e to 1e-11
#    relative error, peak exactly P at t=T.
# ============================================================================================
def twitch_kernel(t, T, P):
    """Vectorized critically-damped 2nd-order twitch impulse response, peak P at t=T."""
    t = np.asarray(t, dtype=float)
    out = np.zeros_like(t)
    m = t >= 0
    out[m] = P * (t[m] / T) * np.exp(1.0 - t[m] / T)
    return out


def twitch_integral(T, P):
    """Exact closed form of integral_0^inf h(t) dt = P*T*e (derived alongside the kernel)."""
    return P * T * math.e


