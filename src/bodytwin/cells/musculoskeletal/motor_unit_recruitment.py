# 3. Motor-unit pool construction (soleus parameterization).
# ============================================================================================
def build_pool(N=120, RR=50.0, TH_MAX=0.95, FORCE_RANGE=100.0,
               CT_MAX=0.100, CT_MIN=0.030, FR_MIN=8.0,
               FR_PEAK_LO=15.0, FR_PEAK_HI=30.0, onion_skin=False):
    """Build a size-ordered motor-unit pool. Unit index i=0..N-1 IS the size rank (smallest
    first) -- this is Henneman's principle stated as a construction rule, not yet a claim.
    What is NOT given for free (checked downstream, Sec. 4/5): that a noisy renewal process
    preserves this order in its raw output, and that the ordering (as opposed to merely the
    threshold distribution) causes the force curve's shape.

    RR: threshold range ratio (largest/smallest), GENERIC parameter -- Fuglevand 1993's
        value is behind a paywall (Sec. 0), swept over {30,50,80} downstream for robustness.
    TH_MAX=0.95: REAL, from Oya et al. 2009 ('close to 95% of MVC').
    FORCE_RANGE=100.0: REAL, from Milner-Brown/Stein/Yemm 1973 (0.1-10 g measured => 100:1).
    CT_MAX/CT_MIN=100/30 ms: REAL RANGE, same paper (contraction times 30-100 ms); assigned by
        rank (largest units = shortest CT), linear-in-rank -- a disclosed simplification of the
        paper's (more skewed, ">80% <70ms") empirical distribution.
    FR_MIN=8 pps: GENERIC (order-of-magnitude consistent with the intramuscular-EMG literature,
        not independently verified).
    FR_PEAK_LO/HI=15/30 pps: GENERIC magnitude; the DIRECTION (which end of the pool gets which)
        is set by `onion_skin` and is muscle-specific, per Oya 2009 (soleus = anti-onion-skin,
        onion_skin=False) vs De Luca & Contessa 2012 (classic, onion_skin=True).
    """
    i = np.arange(1, N + 1)
    x = i / N  # rank fraction in (0,1]

    b_th = math.log(RR)
    threshold = TH_MAX * np.exp(b_th * (x - 1.0))  # threshold[-1] == TH_MAX exactly

    b_f = math.log(FORCE_RANGE)
    force_raw = np.exp(b_f * (x - 1.0))
    twitch_force = force_raw / force_raw[0]  # normalize unit-0 (smallest) to exactly 1.0

    contraction_time = CT_MAX - (CT_MAX - CT_MIN) * x  # unit N-1 -> exactly CT_MIN

    if onion_skin:
        fr_peak = FR_PEAK_HI - (FR_PEAK_HI - FR_PEAK_LO) * x   # decreasing with rank (classic)
    else:
        fr_peak = FR_PEAK_LO + (FR_PEAK_HI - FR_PEAK_LO) * x   # increasing with rank (soleus/Oya)

    return {
        "N": N, "RR": RR, "TH_MAX": TH_MAX, "onion_skin": onion_skin,
        "threshold": threshold, "twitch_force": twitch_force,
        "contraction_time": contraction_time, "fr_min": FR_MIN, "fr_peak": fr_peak,
    }


def firing_rate(E, threshold, fr_min, fr_peak):
    """Linear in excitatory drive between threshold and peak (Fuglevand 1993 abstract, verbatim
    structure). Peak reached at E=1 for every unit (disclosed simplification, Sec. 3 of doc).
    E may be scalar or array; threshold/fr_peak are per-unit arrays (or matching scalars).
    Shared by every experiment below so the rate law lives in exactly one place."""
    E = np.asarray(E, dtype=float)
    active = E >= threshold
    frac = np.clip((E - threshold) / (1.0 - threshold), 0.0, 1.0)
    return np.where(active, fr_min + (fr_peak - fr_min) * frac, 0.0)


