# 7. Experiment C -- recruitment vs rate-coding decomposition (Milner-Brown & Stein 1975 anchor).
# ============================================================================================
def run_experiment_c(rr=50.0):
    out = {}
    for onion_skin, label in [(False, "soleus_anti_onion_skin"), (True, "classic_onion_skin")]:
        pool = build_pool(RR=rr, onion_skin=onion_skin)
        threshold, force, ct = pool["threshold"], pool["twitch_force"], pool["contraction_time"]
        fr_min, fr_peak = pool["fr_min"], pool["fr_peak"]
        unit_integral = twitch_integral(ct, force)
        E_grid = np.linspace(0.02, 1.0, 60)

        def rate_at(E):
            return firing_rate(E, threshold, fr_min, fr_peak), (E >= threshold)

        prev_rate, prev_active = rate_at(E_grid[0])
        prev_F = np.sum(prev_rate * unit_integral)
        recruit_fracs, E_mid = [], []
        for k in range(1, len(E_grid)):
            cur_rate, cur_active = rate_at(E_grid[k])
            cur_F = np.sum(cur_rate * unit_integral)
            dF = cur_F - prev_F
            newly_active = cur_active & (~prev_active)
            still_active = cur_active & prev_active
            recruit_contrib = np.sum(cur_rate[newly_active] * unit_integral[newly_active])
            rate_contrib = np.sum((cur_rate[still_active] - prev_rate[still_active]) *
                                   unit_integral[still_active])
            # machine self-check: this decomposition is claimed EXACT (no cross term) --
            # verify it on every step, not just assert it in prose.
            assert abs((recruit_contrib + rate_contrib) - dF) <= 1e-6 * max(abs(dF), 1e-12), \
                "recruitment+rate-coding decomposition must exactly reconstruct dF"
            frac = recruit_contrib / dF if dF > 0 else float("nan")
            recruit_fracs.append(frac)
            E_mid.append(0.5 * (E_grid[k] + E_grid[k - 1]))
            prev_rate, prev_active, prev_F = cur_rate, cur_active, cur_F
        recruit_fracs = np.array(recruit_fracs)
        E_mid = np.array(E_mid)
        valid = ~np.isnan(recruit_fracs)
        rho = spearman_rho(E_mid[valid], recruit_fracs[valid])
        out[label] = {
            "spearman_E_vs_recruit_fraction": rho,
            "recruit_fraction_low_E_mean": float(recruit_fracs[valid][:10].mean()),
            "recruit_fraction_high_E_mean": float(recruit_fracs[valid][-10:].mean()),
            "pass_gate": bool(rho <= GATE_RECRUIT_FRACTION_SPEARMAN_MAX),
        }
    return out


